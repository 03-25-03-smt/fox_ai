def get_mode(key: str | None, default: str = "chat") -> Mode:
    return MODES.get(key or default) or MODES["chat"]


def style_instructions(persona: str | None, length: str | None) -> str:
    parts = []
    if persona:
        parts.append(f"Твоя роль и стиль, заданные пользователем: {persona}")
    if length and length in LENGTHS and LENGTHS[length][1]:
        parts.append(LENGTHS[length][1])
    return "\n\n".join(parts)
